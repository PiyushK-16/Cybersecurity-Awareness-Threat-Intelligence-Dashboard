def main():
    xml = ROOT / "tests" / ".junit.xml"
    subprocess.run([sys.executable, "-m", "pytest", "-q", f"--junitxml={xml}"], cwd=ROOT)
    outcome = {}
    for tc in ET.parse(xml).getroot().iter("testcase"):
        tid = tc.get("name").split("_")[1].upper()
        outcome[tid] = "FAIL" if tc.find("failure") is not None or tc.find("error") is not None else "PASS"
    lines = ["# Test report", "", "Generated by `python tests/generate_test_report.py`.", "",
             "| Test ID | Scenario | Input | Expected result | Actual result | Pass/Fail |", "|---|---|---|---|---|---|"]
    for tid, scen, inp, exp in CASES:
        res = outcome.get(tid, "NOT RUN")
        actual = "Matched expected" if res == "PASS" else "See pytest output"
        lines.append(f"| {tid} | {scen} | {inp} | {exp} | {actual} | {res} |")
    passed = sum(1 for v in outcome.values() if v == "PASS")
    lines += ["", f"**{passed}/{len(CASES)} tests passed.**"]
    (ROOT / "docs" / "TEST_REPORT.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    xml.unlink(missing_ok=True)
    print(f"Wrote docs/TEST_REPORT.md ({passed}/{len(CASES)} passed)")

if __name__ == "__main__":
    main()
